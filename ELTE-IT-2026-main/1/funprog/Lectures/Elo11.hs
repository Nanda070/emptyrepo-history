reverseF :: [a] -> [a]
--verseF ls =foldL (переворот (:)) [] ls
reverseF ls = foldl (\ acc x -> x : acc) [] ls

flip' :: (a -> b -> c) -> (b -> a -> c)
--перевернуть' f y x = f x y
flip' f = (\a b -> f b a)

-- что происходит: флип' заменяется на (\a b -> элемент b a)

(+:+) :: [a] -> [a] -> [a]

