--(+:+) ls ks =foldr (:) ks ls
(+:+) = flip $ foldr (:)

length' :: [a] -> Int
length' ls = foldr (\_ acc -> 1 + acc) 0 ls

mapF :: (a -> b) -> [a] -> [b]
mapF f ls = foldr(\e xs -> f e : xs) [] ls

mapF' :: (a -> b) -> [a] -> [b]
mapF' f ls = foldr step [] ls where
  step e xs = f e : xs

--мы не можем использовать лямбду для разделения регистра
filterF :: (a -> Bool) -> [a] -> [a]
filterF p ls = foldr step [] ls where
  step e xs
    | p e = e : xs
    | otherwise = xs

and' :: [Bool] -> Bool
and' = foldr (&&) True
and'' ls = foldl (&&) True ls 

--Foldr намного эффективнее
--если мы знаем, что наша функция может по какой-то причине остановиться в середине работы, уместнее использоватьfoldr
--если вам абсолютно необходимо просмотреть список, не имеет значения, какой из них вы используете

--универсальная функция-квантификатор
all' :: (a -> Bool) -> [a] -> Bool
all' p ls = foldr (\e xs -> p e && xs) True ls

-- Функциональная композиция

-- (f(g x)) -> (f o g) x
-- (.) композиция функции, оператор высшего порядка
-- создает третью из двух функций

(.) :: (b -> c) -> (a -> b) -> (a -> c) 
(.) f g x = f (g x)

(.) f g = h where
  h x = f (g x)

(.) f g = (\x -> f (g x))
