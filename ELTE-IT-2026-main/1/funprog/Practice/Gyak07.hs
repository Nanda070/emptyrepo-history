-- Давайте переопределим поэлементную обработку с помощью рекурсии! (карта')
map' :: (a -> b) -> [a] -> [b]
map' _ [] = []
map' f (x:xs) = f x : map' f xs

-- Давайте переопределим поэлементную обработку с помощью генератора списков! (папка'')
map'' :: (a -> b) -> [a] -> [b]
map'' f (x:xs) = [f x | x <- xs]

-- Давайте переопределим фильтрацию с помощью рекурсии! (фильтр')
filter' :: (a -> Bool) -> [a] -> [a]
filter' _ [] = []
filter' p (x:xs)
  | p x = x : filter' p xs
  | otherwise = filter' p xs

-- Давайте переопределим фильтрацию с помощью генератора списков! (фильтр'')
filter'' :: (a -> Bool) -> [a] -> [a]
filter'' p (x:xs) = [x | x <- xs, p x]

-- Давайте подсчитаем количество вхождений элемента с заданным свойством в список!
filtercount :: (a -> Bool) -> [a] -> Int
filtercount _ [] = 0
filtercount p (x:xs)
  | p x = 1 + filtercount p xs
  | otherwise = filtercount p xs
filtercount' :: (a -> Bool) -> [a] -> Int
filtercount' p ls = sum([1 | x <- ls,p x])

-- Давайте переопределим функцию takeWhile!
takeWhile' :: (a -> Bool) -> [a] -> [a]
takeWhile' _ [] = []
takeWhile' p (x:xs)
  | p x = x : takeWhile' p xs
  | otherwise = []

