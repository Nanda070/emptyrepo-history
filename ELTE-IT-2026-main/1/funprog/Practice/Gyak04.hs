--Дан список, содержащий координаты (x,y).
--Давайте выберем координаты, которые находятся на оси X!
onX :: Integral a => [(a,a)] -> [(a,a)]
onX n = [(x,0) | (x,0) <- n]

--Посчитаем пары в списке, в которых расстояние между элементами пары не менее 2!
countPairCon :: Integral a => [(a,a)] -> a
countPairCon n = sum([1 | (x,y) <- n, abs(x-y) >= 2])

