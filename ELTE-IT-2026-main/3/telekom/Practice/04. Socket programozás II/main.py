import socket

soc = socket.socket(socket.AF_INET, socket.SOCK_STREAM)

# Таймаут сокета (таймаут: автоматическое отключение через определенное время, если не происходит определенного события)
soc.settimeout(1.0)     # время ожидания составляет 1 секунду
soc.settimeout(None)    # отключить таймаут
soc.setblocking(True)   # == сокет.settimeout(нет)
soc.setblocking(False)  # == сокет.settimeout(0.0)


# Для дальнейшей тонкой настройки сокетов мы можем использовать
# Метод socket.setsockopt(level, optname, value)
# уровень:
# сокет.IPPROTO_IP: настройка уровня IP
# socket.SOL_SOCKET: настройка уровня API сокета
# имя_опции:
# сокет.REUSEADDR: повторно использовать порт сразу после отключения
# значение: Нет, целое число, неопределенные байты
soc.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)

