import struct
# Модуль struct предоставляет возможность присваивать значения (через объекты python bytes)
# Преобразование в структуры C.
# https://docs.python.org/3/library/struct.html

# Преобразование определяется следующими спецификациями формата:
# https://docs.python.org/3/library/struct.html#struct-format-strings

# Возвращает байтовый объект, содержащий указанные значения v1, v2,... в указанном формате.
# struct.pack(формат, v1, v2, ...)
values = (1, b'ab', 2.7)

# * оператор распространения
packed = struct.pack('l 2s f', *values)  # Значение формата: int, char[2], float
print(packed)

# Распаковать структуру, хранящуюся в виде байтов, в соответствии с указанным форматом.
# struct.unpack(формат, буфер)
unpacked = struct.unpack('l 2s f', packed)
print(unpacked)


# Получить размер структуры
print(struct.calcsize('l 2s f'))  # int: 4 char[2]: 2 с плавающей запятой: 4
# очевидно неправильный результат (10 != 12), поскольку структура использует собственное выравнивание, помещает числа в определенное место в памяти.
# начальная позиция которого делится на размер шрифта

print()
# альтернативный метод лечения
myStruct = struct.Struct('l 2s f')
packed = myStruct.pack(*values)
print(packed)
unpacked = myStruct.unpack(packed)
print(unpacked)
print(myStruct.size)

# Управление файлами
# файлы также можно открыть в двоичном виде, указав «b».
# С помощью f.seek(offset, откуда) вы можете установить указатель доступа к файлу, например. f.seek(0) переходит в начало файла
# для чтения двоичных файлов мы используем метод f.read(int bytes)

with open("database.bin", "rb") as file:
    file.seek(2)  # переходит на второй байт файла (для двоичного файла, на второй символ для текстового файла)
    unpacker = struct.Struct('i3si')  # все равно файл не в этом формате, поэтому интересно, как работает программа
    line = file.read(unpacker.size)
    data = unpacker.unpack(line)
    print(data)

