# Программирование сокетов
# сокет: конечная точка связи
# программа записывает и читает в сокет другой программы через свой собственный сокет
# связь требует знания идентификаторов друг друга (IP-адрес и номер порта)
# Вместо IP-адреса можно использовать уникальный идентификатор, например. www.elte.hu (это сопоставление выполняется сервером доменных имен)
# специальный локальный хост 127.0.0.1

import socket

hostname1 = socket.gethostname()  # имя хоста машины, на которой работает интерпретатор Python
print(hostname1)
hostip = socket.gethostbyname('www.example.org')  # имя хоста -> IP-адрес
host1 = socket.gethostbyname_ex('www.example.org')  # получение подробной информации о хосте по адресу
# (имя хоста, список псевдонимов, список ipaddr) возвращает упорядоченную тройку
print(*host1)
host2 = socket.gethostbyaddr('157.181.161.79')  # получение подробной информации о хосте по адресу на основе IP
# возвращает упорядоченную тройку
print(*host2)

print(socket.getservbyport(22))  # получение службы, работающей под заданным портом

# важная проблема совместимости заключается в том, что порядок байтов может различаться между хостом и сетью.
socket.htons(25)  # короткое замыкание между хостом и сетью
socket.htonl(32)  # хост в сети длинный
socket.ntohs(25)  # сеть для размещения короткого
socket.ntohl(32)  # сеть для размещения долго
