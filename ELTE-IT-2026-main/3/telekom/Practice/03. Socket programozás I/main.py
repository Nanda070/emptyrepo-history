import socket


# Существует два распространенных типа каналов связи:
# пакеты, ориентированные на установление соединения (например, телефонные разговоры), приходят в правильном порядке
# TCP (протокол управления передачей), сокет типа потока
# модель без установления соединения (например, почтовая корреспонденция), порядок посылки не определен, она может быть потеряна, более высокая производительность
# UDP (протокол пользовательских дейтаграмм), сокет типа дейтаграммы


s = socket.socket(family=socket.AF_INET, type=socket.SOCK_STREAM, proto=0)
# сокет.AF_INET — IPv4
# сокет.AF_INET6 — IPv6
# сокет.SOCK_STREAM — ориентированный на соединение (потоковый сокет)
# сокет.DGRAM — без установления соединения (сокет дейтаграммы)
# прото — протокол (необязательно, по умолчанию = 0)


# Связывать
s.bind(('localhost', 10000))  # имя хоста или IP и порт
# 127.0.0.1 = локальный хост


# Инструкция сокета для прослушивания запросов на соединение
s.listen(2)
# отставание: максимальное количество клиентов, ожидающих подключения


other_socket = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
other_socket.bind(('localhost', 5000))


# Отправьте запрос на подключение к удаленному сокету
other_socket.connect(('localhost', 10000))


# Прием запроса на подключение
connection, client_address = s.accept()
# Возврат: (conn, адрес) кортеж
# conn: новый объект сокета, через который мы можем общаться
# адрес: адрес, привязанный к сокету на другой стороне соединения


# Передача данных
# Other_socket.send("Hello World!".encode(), 0) # .encode(): str -> bytes
# данные: байты
# флаги: [] по умолчанию: нет флага = 0
# Возврат: количество переданных байт, приложение должно проверить, все ли оно получило


# Отправка данных, пока они есть
other_socket.sendall("Hello World2!".encode())
# Возврат: Нет в случае успеха
# если он останавливается с ошибкой, невозможно определить количество переданных байтов


# Прием данных
data = connection.recv(1024, 0)
# bufsize — размер данных, которые можно получить одновременно
# флаги
# Возврат: байты


print(data.decode())


connection.close()
s.close()
other_socket.close()
